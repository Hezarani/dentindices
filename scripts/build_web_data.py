"""Embed the index registry in the web app (docs/indices-data.js).

    python scripts/build_web_data.py

The browser app makes no network requests, so the registry (dentindices/data/indices.json) is copied into a
small script that sets ``globalThis.DENTINDICES_REGISTRY``. tests/test_web_engine.py fails if the
embedded copy differs from the JSON file, so the two can never drift apart.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render() -> str:
    reg = json.loads((ROOT / "dentindices" / "data" / "indices.json").read_text(encoding="utf-8"))
    version = re.search(r'__version__ = "([^"]+)"', (ROOT / "dentindices" / "__init__.py").read_text()).group(1)
    reg["package_version"] = version
    body = json.dumps(reg, ensure_ascii=False, separators=(",", ":"))
    return ("/* Generated by scripts/build_web_data.py from dentindices/data/indices.json - do not edit. */\n"
            f"globalThis.DENTINDICES_REGISTRY = {body};\n")


def render_examples() -> str:
    ex = ROOT / "dentindices" / "data" / "examples"
    data = {f.name: f.read_text(encoding="utf-8") for f in sorted(ex.glob("*.csv"))}
    body = json.dumps(data, ensure_ascii=False)
    return ("/* Generated by scripts/build_web_data.py from dentindices/data/examples - do not edit. "
            "Synthetic data, no real people. */\n"
            f"globalThis.DENTINDICES_EXAMPLES = {body};\n")


def main() -> None:
    (ROOT / "docs" / "indices-data.js").write_text(render(), encoding="utf-8")
    (ROOT / "docs" / "examples-data.js").write_text(render_examples(), encoding="utf-8")
    print("wrote docs/indices-data.js and docs/examples-data.js")


if __name__ == "__main__":
    main()
